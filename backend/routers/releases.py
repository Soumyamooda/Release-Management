@router.get("/", response_model=List[ReleaseResponse])
def get_all_releases(db: Session = Depends(get_db)):
    """List releases."""
    releases = db.query(Release).options(joinedload(Release.project), joinedload(Release.manager)).all()
    releases = [
        r for r in releases
        if not is_excluded_project_name(r.project.project_name if r.project else None)
    ]
    return [_to_response(r) for r in releases]


