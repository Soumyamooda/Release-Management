def create_release(release: ReleaseCreate, db: Session = Depends(get_db)):
    """
    Create a release.
    
    Ensures:
    - release_id is auto-generated
    - project_id is properly validated
    - release is immediately available with all auto-generated fields
    """
    # Validate project exists if project_id is provided
    if release.project_id:
        project = db.query(Project).filter(Project.project_id == release.project_id).first()
        if not project:
            raise HTTPException(status_code=400, detail="Project not found")
    
    # Create release with auto-generated release_id
    db_release = Release(**release.model_dump())
    db.add(db_release)
    db.flush()  # Ensures release_id is auto-generated
    db.commit()
    db.refresh(db_release)
    
    # Fetch complete release with project relationship loaded
    r = db.query(Release).options(joinedload(Release.project)).filter(
        Release.release_id == db_release.release_id
    ).first()
    return _to_response(r)


