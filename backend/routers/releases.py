from typing import List
from fastapi import APIRouter, Depends, HTTPException, status
from sqlalchemy.orm import Session, joinedload

from database import get_db
from models import Release, Project
from project_filters import is_excluded_project_name
from schemas import ReleaseCreate, ReleaseUpdate, ReleaseResponse

router = APIRouter(prefix="/releases", tags=["Releases"])


def _to_response(r: Release) -> ReleaseResponse:
    """Normalize release model to response schema."""
    owner = None
    if r.manager:
        owner = r.manager.name
    elif r.project and r.project.manager:
        owner = r.project.manager.name
    score = r.security_score
    readiness_pct = int(score) if score is not None else 0
    return ReleaseResponse(
        release_id=r.release_id,
        release_name=r.release_name,
        project_id=r.project_id,
        project_name=r.project.project_name if r.project else None,
        status=r.status,
        version=r.version,
        environment=r.environment,
        release_date=r.release_date,
        release_summary=r.release_summary,
        security_score=float(r.security_score) if r.security_score is not None else None,
        ai_risk_score=float(r.ai_risk_score) if r.ai_risk_score is not None else None,
        readiness_pct=readiness_pct,
        owner=owner,
        target_date=r.release_date,
        created_at=r.created_date,
    )


